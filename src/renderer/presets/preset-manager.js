class PresetManager {
  constructor() {
    this.presets = { ...DEFAULT_PRESETS };
    this.userPresets = {};
    this.loadUserPresets();
  }

  loadUserPresets() {
    try {
      if (typeof localStorage !== 'undefined') {
        const raw = localStorage.getItem('spectrometer_custom_presets');
        if (raw) {
          this.userPresets = JSON.parse(raw);
          for (const [id, data] of Object.entries(this.userPresets)) {
            this.presets[id] = data;
          }
        }
      }
    } catch (e) {
      console.warn('Could not load user presets from localStorage:', e);
    }
  }

  saveUserPreset(name, presetData) {
    const id = 'custom_' + Date.now() + '_' + Math.random().toString(36).substr(2, 4);
    const fullPreset = {
      ...presetData,
      id,
      name: name || 'Custom Preset',
      isCustom: true
    };
    this.presets[id] = fullPreset;
    this.userPresets[id] = fullPreset;

    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('spectrometer_custom_presets', JSON.stringify(this.userPresets));
      }
    } catch (e) {
      console.warn('Could not save user preset to localStorage:', e);
    }
    return fullPreset;
  }

  deleteUserPreset(id) {
    if (this.userPresets[id]) {
      delete this.userPresets[id];
      delete this.presets[id];
      try {
        if (typeof localStorage !== 'undefined') {
          localStorage.setItem('spectrometer_custom_presets', JSON.stringify(this.userPresets));
        }
      } catch (e) {
        console.warn('Could not delete user preset:', e);
      }
      return true;
    }
    return false;
  }

  exportPresetJSON(id) {
    const p = this.getPreset(id);
    if (!p) throw new Error('Preset not found: ' + id);
    return JSON.stringify(p, null, 2);
  }

  importPresetJSON(jsonStr) {
    const data = JSON.parse(jsonStr);
    if (!data || typeof data !== 'object') throw new Error('Invalid preset JSON');
    const name = data.name || 'Imported Preset';
    return this.saveUserPreset(name, data);
  }

  getPreset(id) {
    return this.presets[id] ? { ...this.presets[id] } : null;
  }

  getPresetList() {
    return Object.keys(this.presets).map(id => ({
      id,
      name: this.presets[id].name,
      isCustom: !!this.presets[id].isCustom
    }));
  }

  saveCustomPreset(id, presetData) {
    this.presets[id] = { ...presetData };
  }
}

